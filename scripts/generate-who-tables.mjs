#!/usr/bin/env node
/**
 * Regenerates `packages/shared/src/growth/whoTables.ts` from the WHO source
 * files in `packages/shared/who-data/`.
 *
 *   node scripts/generate-who-tables.mjs
 *
 * The source files are the daily LMS tables of the WHO Child Growth Standards,
 * copied unchanged from WHO's own repository (see who-data/README.md). Only the
 * first MAX_AGE_DAYS + 1 days are emitted: the app compares infants up to two
 * years, and shipping five years of daily rows to every browser would buy
 * nothing.
 *
 * The output is generated and committed; it is never edited by hand.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(root, 'packages/shared/who-data');
const outFile = join(root, 'packages/shared/src/growth/whoTables.ts');

/** Day 730 is the last recumbent-length row; from day 731 WHO switches to standing height. */
const MAX_AGE_DAYS = 730;

/** WHO file → indicator name used in the app. */
const SOURCES = {
  weight: 'weianthro.txt',
  length: 'lenanthro.txt',
  headCircumference: 'hcanthro.txt',
};

/** WHO codes sex as 1 = male, 2 = female. */
const SEX = { 1: 'MALE', 2: 'FEMALE' };

function parse(file) {
  const [header, ...rows] = readFileSync(join(sourceDir, file), 'utf8').trim().split(/\r?\n/);
  const columns = header.split('\t');
  const at = (name) => {
    const index = columns.indexOf(name);
    if (index < 0) throw new Error(`${file}: no "${name}" column`);
    return index;
  };
  const [sexAt, ageAt, lAt, mAt, sAt] = ['sex', 'age', 'l', 'm', 's'].map(at);
  const lohAt = columns.indexOf('loh');

  const tables = { MALE: { l: [], m: [], s: [] }, FEMALE: { l: [], m: [], s: [] } };
  for (const row of rows) {
    const cells = row.split('\t');
    const age = Number(cells[ageAt]);
    if (age > MAX_AGE_DAYS) continue;
    // Under two years WHO measures recumbent length; a standing-height row here
    // would mean the source is not what this script expects.
    if (lohAt >= 0 && cells[lohAt] !== 'L') throw new Error(`${file}: day ${age} is not length`);
    const table = tables[SEX[cells[sexAt]]];
    if (!table) throw new Error(`${file}: unknown sex ${cells[sexAt]}`);
    if (table.m.length !== age) throw new Error(`${file}: day ${age} out of order`);
    table.l.push(Number(cells[lAt]));
    table.m.push(Number(cells[mAt]));
    table.s.push(Number(cells[sAt]));
  }
  for (const [sex, table] of Object.entries(tables)) {
    if (table.m.length !== MAX_AGE_DAYS + 1)
      throw new Error(`${file}: ${sex} has ${table.m.length} days`);
  }
  return tables;
}

const list = (values) => `[${values.join(',')}]`;

let body = '';
for (const [indicator, file] of Object.entries(SOURCES)) {
  const tables = parse(file);
  body += `  ${indicator}: {\n`;
  for (const sex of ['MALE', 'FEMALE']) {
    const { l, m, s } = tables[sex];
    body += `    ${sex}: {\n      l: ${list(l)},\n      m: ${list(m)},\n      s: ${list(s)},\n    },\n`;
  }
  body += '  },\n';
}

const output = `/**
 * GENERATED by scripts/generate-who-tables.mjs — do not edit by hand.
 *
 * WHO Child Growth Standards, daily LMS parameters, birth to day ${MAX_AGE_DAYS}.
 * Source and provenance: packages/shared/who-data/README.md.
 *
 * Units: weight kg, length cm, head circumference cm. Index = age in days.
 */
import type { WhoLmsTables } from './who.js';

export const WHO_MAX_AGE_DAYS = ${MAX_AGE_DAYS};

export const WHO_TABLES: WhoLmsTables = {
${body}};
`;

writeFileSync(outFile, output);
console.log(`wrote ${outFile}`);
